"""
Generates src/LifeOS.Pdf/Fonts/Standard/StandardFontMetrics.Generated.cs from the
Adobe Core14 AFM files.

Developer-only tool; the generated C# file is committed, the AFM files are not.

    pip install fonttools
    # AFM files: Adobe Core14 metrics, e.g. from the Apache PDFBox repository
    # (pdfbox/src/main/resources/org/apache/pdfbox/resources/afm/*.afm)
    python tools/generate_afm_metrics.py <folder-with-afm-files>

Text fonts are indexed by WinAnsiEncoding code (32-255): each code is decoded
with Windows-1252, mapped to an Adobe glyph name, and looked up in the AFM.
Symbol and ZapfDingbats are indexed by their built-in encoding (AFM "C" codes).
"""
import os
import sys

from fontTools import agl

FONTS = [
    ("Helvetica", "Helvetica"),
    ("HelveticaBold", "Helvetica-Bold"),
    ("HelveticaOblique", "Helvetica-Oblique"),
    ("HelveticaBoldOblique", "Helvetica-BoldOblique"),
    ("TimesRoman", "Times-Roman"),
    ("TimesBold", "Times-Bold"),
    ("TimesItalic", "Times-Italic"),
    ("TimesBoldItalic", "Times-BoldItalic"),
    ("Courier", "Courier"),
    ("CourierBold", "Courier-Bold"),
    ("CourierOblique", "Courier-Oblique"),
    ("CourierBoldOblique", "Courier-BoldOblique"),
    ("Symbol", "Symbol"),
    ("ZapfDingbats", "ZapfDingbats"),
]

# ISO 32000-1 Annex D: in WinAnsiEncoding, 0xA0 is "space" and 0xAD is "hyphen".
WINANSI_OVERRIDES = {0xA0: "space", 0xAD: "hyphen"}


def parse_afm(path):
    header, by_name, by_code = {}, {}, {}
    in_metrics = False
    with open(path, encoding="latin-1") as f:
        for line in f:
            line = line.strip()
            if line.startswith("StartCharMetrics"):
                in_metrics = True
                continue
            if line.startswith("EndCharMetrics"):
                in_metrics = False
                continue
            if in_metrics:
                if not line.startswith("C "):
                    continue  # blank lines inside the metrics block
                fields = dict(
                    part.strip().split(" ", 1) for part in line.split(";") if part.strip() and " " in part.strip()
                )
                code, width, name = int(fields["C"]), int(fields["WX"]), fields["N"]
                by_name[name] = width
                if code >= 0:
                    by_code[code] = width
            elif " " in line:
                key, value = line.split(" ", 1)
                header[key] = value
    return header, by_name, by_code


def winansi_name(code):
    if code in WINANSI_OVERRIDES:
        return WINANSI_OVERRIDES[code]
    try:
        ch = bytes([code]).decode("cp1252")
    except UnicodeDecodeError:
        return None  # 0x81, 0x8D, 0x8F, 0x90, 0x9D are undefined
    return agl.UV2AGL.get(ord(ch))


def main(afm_dir):
    out = []
    out.append("// <auto-generated>")
    out.append("// Generated by tools/generate_afm_metrics.py from the Adobe Core14 AFM files.")
    out.append("// Do not edit by hand. Widths in 1/1000 em for codes 32-255.")
    out.append("// </auto-generated>")
    out.append("namespace LifeOS.Pdf.Fonts.Standard")
    out.append("{")
    out.append("    internal static partial class StandardFontData")
    out.append("    {")
    out.append("        private static StandardFontData.Entry Create(StandardFont font)")
    out.append("        {")
    out.append("            switch (font)")
    out.append("            {")

    for enum_name, file_name in FONTS:
        header, by_name, by_code = parse_afm(os.path.join(afm_dir, file_name + ".afm"))
        builtin = file_name in ("Symbol", "ZapfDingbats")
        widths, missing = [], []
        for code in range(32, 256):
            if builtin:
                widths.append(by_code.get(code, 0))
                continue
            name = winansi_name(code)
            if name is None:
                widths.append(0)
            elif name in by_name:
                widths.append(by_name[name])
            else:
                widths.append(0)
                missing.append(f"{code:#x}:{name}")
        if missing:
            print(f"{file_name}: no AFM width for {missing}", file=sys.stderr)

        bbox = [int(v) for v in header["FontBBox"].split()]
        ascent = int(header.get("Ascender", bbox[3]))
        descent = int(header.get("Descender", bbox[1]))
        cap = int(header.get("CapHeight", ascent))
        italic = float(header.get("ItalicAngle", "0"))
        stemv = int(header.get("StdVW", "80"))
        fixed = header.get("IsFixedPitch", "false").strip() == "true"

        rows = []
        for i in range(0, len(widths), 16):
            rows.append("                        " + ", ".join(str(w) for w in widths[i:i + 16]) + ",")
        out.append(f"                case StandardFont.{enum_name}:")
        out.append(f"                    return new Entry(\"{file_name}\", {ascent}, {descent}, {cap}, {italic!r}, {stemv}, "
                   f"{'true' if fixed else 'false'}, {'true' if builtin else 'false'}, "
                   f"new short[] {{ {bbox[0]}, {bbox[1]}, {bbox[2]}, {bbox[3]} }}, new short[]")
        out.append("                    {")
        out.extend(rows)
        out.append("                    });")

    out.append("                default:")
    out.append("                    throw new System.ArgumentOutOfRangeException(nameof(font), font, \"Unknown standard font.\");")
    out.append("            }")
    out.append("        }")
    out.append("    }")
    out.append("}")

    target = os.path.join(os.path.dirname(__file__), "..", "src", "LifeOS.Pdf", "Fonts", "Standard",
                          "StandardFontMetrics.Generated.cs")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(target))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1])
