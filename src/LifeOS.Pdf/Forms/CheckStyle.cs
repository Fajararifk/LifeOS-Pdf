namespace LifeOS.Pdf.Forms
{
    /// <summary>The glyph drawn inside a checkbox or radio button when it is on.</summary>
    public enum CheckStyle
    {
        /// <summary>A check mark, the default for checkboxes.</summary>
        Check,

        /// <summary>A cross (X).</summary>
        Cross,

        /// <summary>A five-pointed star.</summary>
        Star,

        /// <summary>A filled circle, the default for radio buttons.</summary>
        Circle,

        /// <summary>A filled square.</summary>
        Square,
    }
}
